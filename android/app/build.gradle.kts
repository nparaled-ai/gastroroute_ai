// La clave del mapa sale de android/local.properties, que git ignora.
//
// Una clave de Android se puede extraer del APK, asi que lo que de verdad la
// protege es su restriccion (paquete + huella SHA-1) y no el secreto. Aun asi
// no se mete en el repositorio: una clave publicada en GitHub la encuentran los
// rastreadores en minutos, y aunque no sirva fuera de la app, Google avisa y
// hay que rotarla.
//
// Sin clave el mapa sale gris, pero la app compila y todo lo demas funciona.
val mapsApiKey: String = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}.getProperty("MAPS_API_KEY") ?: ""

